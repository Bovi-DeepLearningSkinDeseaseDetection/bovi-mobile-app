// Packs the parity images and their expected results into a Dart file, so the
// integration test can carry them to the phone without adding them to the app.
//
// Run from the project root:
//   dart run tool/generate_parity_fixtures.dart
import 'dart:convert';
import 'dart:io';

const _source = 'test/fixtures/paridad';
const _target = 'integration_test/parity_fixtures.g.dart';

void main() {
  final expectedFile = File('$_source/esperado.json');
  if (!expectedFile.existsSync()) {
    stderr.writeln('No se encontró $_source/esperado.json');
    exitCode = 1;
    return;
  }
  final expected = expectedFile.readAsStringSync().trim();
  final cases = (jsonDecode(expected) as Map<String, dynamic>)['casos'] as List;

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_parity_fixtures.dart.')
    ..writeln('// Do not edit by hand: run the script again instead.')
    ..writeln()
    ..writeln('/// Content of test/fixtures/paridad/esperado.json.')
    ..writeln("const parityExpectedJson = r'''")
    ..writeln(expected)
    ..writeln("''';")
    ..writeln()
    ..writeln('/// Parity images encoded in base64, by file name.')
    ..writeln('const parityImages = <String, String>{');

  for (final item in cases) {
    final name = (item as Map<String, dynamic>)['archivo'] as String;
    final image = File('$_source/$name');
    if (!image.existsSync()) {
      stderr.writeln('Falta la imagen $_source/$name');
      exitCode = 1;
      return;
    }
    out.writeln("  '$name':");
    out.writeln("      '${base64Encode(image.readAsBytesSync())}',");
  }
  out.writeln('};');

  File(_target)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('Listo: $_target (${cases.length} imágenes)');
}
